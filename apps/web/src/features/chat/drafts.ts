/**
 * Заготовки для поля ввода (§3.9): переход в чат с `?draft=` открывает новый тред с заполненным полем и ничего не
 * отправляет. Подключение вуза и источника — это разговор с агентом, а не отдельная форма.
 */
export const CONNECT_DRAFT = "Хочу подключить вуз. Название или ссылка на личный кабинет: ";

/** Заготовка нового источника для вуза; без вуза — подключение вуза целиком. */
export const addSourceDraft = (space: { shortTitle: string } | null): string =>
  space ? `Добавь источник для ${space.shortTitle}: ` : CONNECT_DRAFT;
